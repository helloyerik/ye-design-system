// Single source → CSS vars, TS, Kotlin. Run: npm run tokens. Outputs are committed (consumers need no npm install).
import StyleDictionary from 'style-dictionary'
import { readdirSync } from 'node:fs'

const val = (t) => t.$value ?? t.value
const kebab = (p) => p.join('-')
const camel = (p) => p.join('-').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
const bezier = (v) => `cubic-bezier(${v.join(', ')})`
const cssValue = (t) => { const v = val(t); return Array.isArray(v) ? bezier(v) : typeof v === 'object' ? null : String(v) }

// spring (dampingRatio, stiffness, mass 1) → Apple-style duration/bounce + CSS linear() easing, same math as web motion.ts
// accepts {dampingRatio, stiffness} (native) or {duration, bounce} (Apple/web); both forms are exact in their own unit
export function springNorm(v) {
  if (v.duration != null) { const omega = (2 * Math.PI) / v.duration; return { duration: v.duration, bounce: v.bounce, dampingRatio: +(1 - v.bounce).toFixed(4), stiffness: +(omega * omega).toFixed(2) } }
  const duration = (2 * Math.PI) / Math.sqrt(v.stiffness); return { ...v, duration: +duration.toFixed(4), bounce: +(1 - v.dampingRatio).toFixed(4) }
}
export function springCss(v) {
  const n0 = springNorm(v), zeta = n0.dampingRatio, duration = n0.duration, omega = (2 * Math.PI) / duration
  const wd = omega * Math.sqrt(Math.max(1e-6, 1 - zeta * zeta))
  const x = (t) => zeta >= 1 ? 1 - (1 + omega * t) * Math.exp(-omega * t)
    : 1 - Math.exp(-zeta * omega * t) * (Math.cos(wd * t) + ((zeta * omega) / wd) * Math.sin(wd * t))
  let settle = duration
  for (let t = 0; t < 4 * duration; t += 0.005) if (Math.abs(1 - x(t)) > 0.001) settle = t
  const n = 40, pts = Array.from({ length: n + 1 }, (_, i) => +x((settle * i) / n).toFixed(4)); pts[n] = 1
  return { ...n0, easing: `linear(${pts.join(', ')})`, ms: Math.round(settle * 1000) }
}

const themed = (tokens, mode) => tokens.filter((t) => t.path[0] === 'color' && t.path[1] === mode)
const plain = (tokens) => tokens.filter((t) => t.path[0] !== 'color')

StyleDictionary.registerFormat({
  name: 'ye/css',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens
    const block = (mode) => themed(all, mode).map((t) => `--ye-${t.path.slice(2).join('-')}: ${val(t)};`).join(' ')
    const root = plain(all).flatMap((t) => {
      if (t.path[0] === 'spring') { const s = springCss(val(t)); return [`--ye-${kebab(t.path)}: ${s.easing};`, `--ye-${kebab(t.path)}-dur: ${s.ms}ms;`] }
      const v = cssValue(t); return v == null ? [] : [`--ye-${kebab(t.path)}: ${v};`]
    })
    return [
      '/* GENERATED by ye-design-system tokens/build.mjs — do not edit. */',
      '/* Light = :root default and :root[data-theme=light]. Dark = system dark (unless forced light), [data-theme=dark], .ye-dark. Dark blocks MUST stay identical. */',
      `:root {\n  ${root.join('\n  ')}\n}`,
      `:root, :root[data-theme="light"] { ${block('light')} }`,
      `@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ${block('dark')} } }`,
      `:root[data-theme="dark"], .ye-dark { ${block('dark')} }`, '',
    ].join('\n')
  },
})

StyleDictionary.registerFormat({
  name: 'ye/ts',
  format: ({ dictionary }) => {
    const tree = {}
    for (const t of dictionary.allTokens) {
      let v = val(t)
      if (t.path[0] === 'spring') v = { ...v, ...springCss(v) }
      else if (Array.isArray(v)) v = bezier(v)
      else if (typeof v === 'string' && /^-?[\d.]+(px|ms)$/.test(v)) v = parseFloat(v)
      let node = tree
      t.path.slice(0, -1).forEach((k) => (node = node[k] ??= {}))
      node[t.path.at(-1)] = v
    }
    return `// GENERATED by ye-design-system tokens/build.mjs — do not edit. px/ms are plain numbers.\nexport const tokens = ${JSON.stringify(tree, null, 2)} as const\nexport type Tokens = typeof tokens\n`
  },
})

const argb = (s) => {
  if (s.startsWith('#')) { const h = s.slice(1).toUpperCase(); return h.length === 8 ? '0x' + h.slice(6) + h.slice(0, 6) : '0xFF' + h }
  const [r, g, b, a = 1] = s.match(/rgba?\(([^)]+)\)/)[1].split(',').map(Number)
  const hx = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase()
  return '0x' + hx(a * 255) + hx(r) + hx(g) + hx(b)
}
StyleDictionary.registerFormat({
  name: 'ye/kotlin',
  format: ({ dictionary, options }) => {
    const all = dictionary.allTokens, out = []
    const colors = (mode) => themed(all, mode).map((t) => `        val ${camel(t.path.slice(2))} = Color(${argb(val(t))})`).join('\n')
    out.push(`// GENERATED by ye-design-system tokens/build.mjs — do not edit.\npackage ${options.pkg}\n`)
    out.push('import androidx.compose.animation.core.CubicBezierEasing\nimport androidx.compose.animation.core.spring\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n')
    out.push('object YeTokens {')
    out.push(`    object Light {\n${colors('light')}\n    }`, `    object Dark {\n${colors('dark')}\n    }`)
    const group = (name, pred, fmt) => { const ts = plain(all).filter(pred); if (ts.length) out.push(`    object ${name} {\n${ts.map(fmt).join('\n')}\n    }`) }
    const num = (t) => parseFloat(val(t))
    group('Radius', (t) => t.path[0] === 'radius', (t) => `        val ${camel(t.path.slice(1))} = ${num(t)}.dp`)
    group('Size', (t) => t.path[0] === 'size', (t) => `        val ${camel(t.path.slice(1))} = ${num(t)}.dp`)
    group('Space', (t) => t.path[0] === 'space', (t) => `        val ${camel(t.path.slice(1))} = ${num(t)}.dp`)
    group('Type', (t) => t.path[0] === 'type', (t) => t.path[2] === 'weight' ? `        const val ${camel(t.path.slice(1))} = ${val(t)}` : `        val ${camel(t.path.slice(1))} = ${num(t)}.sp`)
    group('Ease', (t) => t.path[0] === 'ease', (t) => `        val ${camel(t.path.slice(1))} = CubicBezierEasing(${val(t).map((n) => n + 'f').join(', ')})`)
    group('Dur', (t) => t.path[0] === 'dur', (t) => `        const val ${camel(t.path.slice(1))}Ms = ${num(t)}`)
    group('Spring', (t) => t.path[0] === 'spring', (t) => { const s = springNorm(val(t)); return `        fun <T> ${camel(t.path.slice(1))}() = spring<T>(dampingRatio = ${s.dampingRatio}f, stiffness = ${s.stiffness}f)` })
    group('Gesture', (t) => t.path[0] === 'gesture', (t) => typeof val(t) === 'string' ? `        val ${camel(t.path.slice(1))} = ${num(t)}.dp` : `        const val ${camel(t.path.slice(1))} = ${val(t)}f`)
    out.push(`    const val ICON_STROKE = 2f\n    const val FONT_FAMILY = "Figtree"`)
    out.push('}\n')
    return out.join('\n')
  },
})

const apps = ['base', ...readdirSync(new URL('./apps', import.meta.url)).map((f) => f.replace(/\.json$/, ''))]
for (const app of apps) {
  const sd = new StyleDictionary({
    source: ['tokens/base/*.json', ...(app === 'base' ? [] : [`tokens/apps/${app}.json`])],
    usesDtcg: true, log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: {
      web: { transforms: [], buildPath: `build/${app}/`, files: [{ destination: 'tokens.css', format: 'ye/css' }, { destination: 'tokens.ts', format: 'ye/ts' }] },
      kotlin: { transforms: [], buildPath: `build/${app}/`, files: [{ destination: 'YeTokens.kt', format: 'ye/kotlin', options: { pkg: 'ye.designsystem.tokens' } }] },
    },
  })
  await sd.buildAllPlatforms()
  console.log('built', app)
}
